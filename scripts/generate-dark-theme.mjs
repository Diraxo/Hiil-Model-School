// Generates src/theme.css: dark-mode overrides for the Tailwind colour utilities the UI actually uses.
// Light mode is untouched (no rule applies without `html.dark`). Re-run after adding new colour classes:
//   node scripts/generate-dark-theme.mjs
import fs from "node:fs";
import path from "node:path";

const SRC = "src";
const files = [];
(function walk(d) { for (const f of fs.readdirSync(d, { withFileTypes: true })) { const p = path.join(d, f.name); if (f.isDirectory()) walk(p); else if (/\.(jsx?|tsx?)$/.test(f.name)) files.push(p); } })(SRC);
const source = files.map((f) => fs.readFileSync(f, "utf8")).join("\n");

const tint = { red: "239,68,68", amber: "245,158,11", emerald: "16,185,129", blue: "59,130,246", sky: "14,165,233", indigo: "99,102,241", gold: "233,166,60", brand: "209,72,63", rose: "244,63,94", teal: "20,184,166", cyan: "6,182,212", green: "34,197,94" };
const t300 = { red: "#fca5a5", amber: "#fcd34d", emerald: "#6ee7b7", blue: "#93c5fd", sky: "#7dd3fc", indigo: "#a5b4fc", gold: "#eec25c", brand: "#eda19c", rose: "#fda4af", teal: "#5eead4", cyan: "#67e8f9", green: "#86efac" };
const t400 = { red: "#f87171", amber: "#fbbf24", emerald: "#34d399", blue: "#60a5fa", sky: "#38bdf8", indigo: "#818cf8", gold: "#e9a63c", brand: "#e2716b", rose: "#fb7185", teal: "#2dd4bf", cyan: "#22d3ee", green: "#4ade80" };

// property -> (family, shade) -> value | null (leave alone)
function valueFor(prop, fam, shade) {
  const n = Number(shade);
  if (fam === "white") return prop === "bg" || prop === "border" ? "var(--t-surface)" : null;
  if (fam === "slate") {
    if (prop === "bg") return { 50: "var(--t-bg50)", 100: "var(--t-bg100)", 200: "var(--t-bg200)" }[n] ?? null;
    if (prop === "border" || prop === "divide") return { 50: "var(--t-bd50)", 100: "var(--t-bd100)", 200: "var(--t-bd200)", 300: "var(--t-bd300)" }[n] ?? null;
    if (prop === "text") return `var(--t-t${n})`;
    return null;
  }
  if (!tint[fam]) return null;
  if (prop === "bg") return n === 50 ? `rgba(${tint[fam]},.12)` : n === 100 ? `rgba(${tint[fam]},.2)` : n === 200 ? `rgba(${tint[fam]},.28)` : null;
  if (prop === "border") return n === 100 ? `rgba(${tint[fam]},.25)` : n === 200 ? `rgba(${tint[fam]},.35)` : n === 300 ? `rgba(${tint[fam]},.45)` : null;
  if (prop === "text") return n >= 700 ? `var(--t-${fam}-hi, ${t300[fam]})` : n >= 500 ? `var(--t-${fam}-lo, ${t400[fam]})` : null;
  return null;
}

const re = /(?<![\w:-])((?:hover|focus|focus-within|group-hover|placeholder|sm):)?(bg|text|border|divide)-(white|slate|red|amber|emerald|blue|sky|indigo|gold|brand|rose|teal|cyan|green)(?:-(\d+))?(?:\/(\d+))?(?![\w-])/g;
const seen = new Map();
for (const m of source.matchAll(re)) {
  const [full, variant, prop, fam, shade, opacity] = m;
  if (fam === "white" && (opacity || shade)) continue;
  if (fam !== "white" && !shade) continue;
  let v = valueFor(prop, fam, shade);
  if (v == null) continue;
  if (opacity && fam !== "slate" && fam !== "white" && prop === "bg") v = `rgba(${tint[fam]},.12)`;
  if (opacity && fam === "slate") v = "var(--t-bg100)";
  if (opacity && prop !== "bg" && fam !== "white") continue; // e.g. text-red-600/70: keep as is
  seen.set(full, { variant, prop, v });
}

const esc = (c) => c.replace(/([:/\[\]])/g, String.raw`\$1`);
const rules = { base: [], sm: [] };
for (const [cls, { variant, prop, v }] of [...seen].sort()) {
  const c = esc(cls);
  const decl = prop === "bg" ? `background-color:${v}` : prop === "text" ? `color:${v}` : `border-color:${v}`;
  let sel;
  if (prop === "divide") { sel = `html.dark .${c} > :not([hidden]) ~ :not([hidden])`; }
  else if (variant === "hover:") sel = `html.dark .${c}:hover`;
  else if (variant === "focus:") sel = `html.dark .${c}:focus`;
  else if (variant === "focus-within:") sel = `html.dark .${c}:focus-within`;
  else if (variant === "group-hover:") sel = `html.dark .group:hover .${c}`;
  else if (variant === "placeholder:") sel = `html.dark .${c}::placeholder`;
  else sel = `html.dark .${c}`;
  (variant === "sm:" ? rules.sm : rules.base).push(`${sel}{${decl}}`);
}

